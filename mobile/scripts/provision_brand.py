def parse_args(argv=None):
    parser = argparse.ArgumentParser(description="Flavor Brand Provisioner for Mobile Apps")
    parser.add_argument("--config-url", type=str, help="WordPress REST API endpoint for brand configuration")
    parser.add_argument("--config-file", type=str, help="Local JSON file with branding parameters")
    parser.add_argument("--mobile-root", type=str, default=".", help="Root directory of Flutter project")
    return parser.parse_args(argv)


def main(argv=None) -> int:
    args = parse_args(argv)

    if args.config_url:
        raw = fetch_config_from_url(args.config_url, mobile_dir=args.mobile_root)
    elif args.config_file:
        raw = load_config_from_file(args.config_file)
    else:
        default_file = os.path.join(args.mobile_root, "assets", "branding", "default_branding.json")
        if os.path.exists(default_file):
            raw = load_config_from_file(default_file)
        else:
            print("[!] Error: You must supply --config-url or --config-file.")
            return 1

    try:
        cfg = normalize_config(raw)
        print(f"[*] Applying white-label configuration for tenant: {cfg['tenant_id']}")
        update_pubspec_yaml(args.mobile_root, cfg)
        update_android_branding(args.mobile_root, cfg)
        update_ios_branding(args.mobile_root, cfg)
        update_android_app_links(args.mobile_root, cfg)
        update_ios_entitlements(args.mobile_root, cfg)
        generate_wellknown_deeplink_files(args.mobile_root, cfg)
        generate_branding_dart_constants(args.mobile_root, cfg)
    except ProvisioningError as e:
        print(f"[✗] Provisioning rejected: {e}")
        return 2

    print("[✓] Brand provisioning completed successfully!")
    return 0


if __name__ == "__main__":
    sys.exit(main())

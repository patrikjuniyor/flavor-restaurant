# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

CANONICAL_SCHEMA_ID = "flavor-mobile-branding@1"

# The native package is an architectural constant: Gradle `namespace` and the
# Kotlin source tree never move, only `applicationId` varies per brand.
STABLE_NATIVE_PACKAGE = "com.flavor.restaurant"

DEFAULTS = {
    "app_name": "Flavor Restaurant",
    "tenant_id": "default_tenant",
    "api_base_url": "https://demo.flavor.restaurant/wp-json/flavor/v2",
    "default_branch_id": 0,
    "branding": {
        "primary_color": "#C62828",
        "secondary_color": "#2E7D32",
        "accent_color": "#FFA000",
        "font_family": "Vazirmatn",
        "border_radius": 12.0,
    },
    "contact": {
        "phone": "021-88888888",
        "email": "support@flavor.restaurant",
        "website": "",
    },
    "legal": {
        "privacy_policy": "",
        "terms": "",
    },
    "assets": {
        "logo_url": "",
        "icon_url": "",
        "splash_url": "",
    },
    "deep_links": {
        "domains": [],
    },
}

# Android package-name rules: dot-separated segments, each starting with a
# letter, containing letters/digits/underscores. Two segments minimum.
APP_ID_RE = re.compile(r"^[a-zA-Z][a-zA-Z0-9_]*(\.[a-zA-Z][a-zA-Z0-9_]*)+$")
MAX_APP_ID_LEN = 255

# Semantic version name: MAJOR.MINOR.PATCH with optional pre-release suffix.
VERSION_NAME_RE = re.compile(r"^\d+\.\d+\.\d+(?:-[0-9A-Za-z.\-]+)?$")
MAX_VERSION_CODE = 2_100_000_000  # Google Play maximum.

HEX_COLOR_RE = re.compile(r"^#[0-9a-fA-F]{6}$")
TENANT_ID_RE = re.compile(r"^[a-z0-9][a-z0-9_\-]{0,63}$")
FONT_FAMILY_RE = re.compile(r"^[\w\- ]{1,64}$")
URL_RE = re.compile(r"^https?://[^\s\"'<>`\\]+$")
HOST_RE = re.compile(r"^[a-z0-9]([a-z0-9\-]{0,61}[a-z0-9])?(\.[a-z0-9]([a-z0-9\-]{0,61}[a-z0-9])?)+\.?$")
CERT_FINGERPRINT_RE = re.compile(r"^([0-9A-Fa-f]{2}:){31}[0-9A-Fa-f]{2}$")
IOS_TEAM_ID_RE = re.compile(r"^[A-Z0-9]{10}$")
MAX_TEXT_LEN = 200


class ProvisioningError(Exception):
    """Raised when a configuration value fails validation or a target file
    cannot be provisioned safely."""


# ---------------------------------------------------------------------------
# Format-specific escaping helpers (defense in depth after validation)
# ---------------------------------------------------------------------------

_CONTROL_CHARS_RE = re.compile(r"[\x00-\x1f\x7f]")


def strip_control_chars(value: str) -> str:
    """Remove control characters (incl. newlines/CR) from a value."""
    return _CONTROL_CHARS_RE.sub("", value)


def escape_dart(value: str) -> str:
    """Escape *value* for embedding inside a single-quoted Dart string literal."""
    value = strip_control_chars(str(value))
    return (
        value.replace("\\", "\\\\")
        .replace("'", "\\'")
        .replace("$", "\\$")
    )


def escape_xml_text(value: str) -> str:
    """Escape *value* for embedding inside XML element text or attribute."""
    value = strip_control_chars(str(value))
    return xml_escape(value, {"\"": "&quot;", "'": "&apos;"})


def escape_gradle_string(value: str) -> str:
    """Escape *value* for embedding inside a double-quoted Groovy string.

    Validated identifiers never need this, but values into Gradle files go
    through here regardless (GString ``$``-interpolation is neutralized).
    """
    value = strip_control_chars(str(value))
    return value.replace("\\", "\\\\").replace('"', '\\"').replace('$', '\\$')


# ---------------------------------------------------------------------------
# Validation
# ---------------------------------------------------------------------------

def _require(condition: bool, message: str) -> None:
    if not condition:
        raise ProvisioningError(message)


def validate_app_identifier(value: str, field: str = "app_identifier") -> str:
    _require(isinstance(value, str), f"{field}: must be a string")
    _require(bool(value.strip()), f"{field}: must not be empty")
    _require(len(value) <= MAX_APP_ID_LEN, f"{field}: longer than {MAX_APP_ID_LEN} characters")
    _require(
        bool(APP_ID_RE.match(value)),
        f"{field}: '{value}' is not a valid application identifier "
        f"(dot-separated segments, letters/digits/underscores, each starting with a letter)",
    )
    return value


def validate_version_name(value: str) -> str:
    value = str(value)
    _require(
        bool(VERSION_NAME_RE.match(value)),
        f"version_name: '{value}' must be semantic (e.g. '1.4.2' or '2.0.0-beta1')",
    )
    return value


def validate_version_code(value) -> int:
    if isinstance(value, bool) or value is None:
        raise ProvisioningError(f"version_code: '{value}' is not an integer")
    if isinstance(value, float) and not value.is_integer():
        raise ProvisioningError(f"version_code: {value} is not an integer")
    if isinstance(value, str) and not re.fullmatch(r"\d+", value.strip()):
        raise ProvisioningError(f"version_code: '{value}' is not an integer")
    code = int(value)
    _require(1 <= code <= MAX_VERSION_CODE, f"version_code: {code} out of range 1..{MAX_VERSION_CODE}")
    return code


def validate_color(value: str, field: str) -> str:
    _require(isinstance(value, str) and bool(HEX_COLOR_RE.match(value)),
             f"{field}: '{value}' must be a 6-digit hex color like '#1A2B3C'")
    return value.upper()


def validate_url(value: str, field: str, allow_empty: bool = True) -> str:
    if value is None:
        value = ""
    value = str(value)
    if value == "":
        _require(allow_empty, f"{field}: must not be empty")
        return value
    _require(bool(URL_RE.match(value)),
             f"{field}: '{value}' is not a valid http(s) URL without whitespace/quotes")
    parsed = urlparse(value)
    _require(bool(parsed.netloc), f"{field}: '{value}' has no host")
    return value


def validate_tenant_id(value: str) -> str:
    _require(isinstance(value, str) and bool(TENANT_ID_RE.match(value)),
             f"tenant_id: '{value}' must be a lowercase slug [a-z0-9_-] up to 64 characters")
    return value


def validate_text(value: str, field: str, allow_empty: bool = False, max_len: int = MAX_TEXT_LEN) -> str:
    _require(isinstance(value, str), f"{field}: must be a string")
    _require(allow_empty or bool(value.strip()), f"{field}: must not be empty")
    cleaned = strip_control_chars(value)
    _require(len(cleaned) <= max_len, f"{field}: longer than {max_len} characters")
    return cleaned


def validate_branch_id(value) -> int:
    try:
        branch = int(value)
    except (TypeError, ValueError):
        raise ProvisioningError(f"default_branch_id: '{value}' is not an integer")
    _require(branch >= 0, f"default_branch_id: {branch} must be >= 0")
    return branch


def validate_font_family(value: str) -> str:
    _require(isinstance(value, str) and bool(FONT_FAMILY_RE.match(value)),
             f"branding.font_family: '{value}' contains disallowed characters")
    return value


def validate_border_radius(value) -> float:
    try:
        radius = float(value)
    except (TypeError, ValueError):
        raise ProvisioningError(f"branding.border_radius: '{value}' is not numeric")
    _require(0.0 <= radius <= 200.0, f"branding.border_radius: {radius} out of range 0..200")
    return radius


def validate_config(cfg: dict) -> dict:
    """Validate the normalized canonical configuration in place."""
    validate_app_identifier(cfg["app_identifier"])
    cfg["version_name"] = validate_version_name(cfg["version_name"])
    cfg["version_code"] = validate_version_code(cfg["version_code"])
    cfg["app_name"] = validate_text(cfg["app_name"], "app_name", max_len=100)
    cfg["tenant_id"] = validate_tenant_id(cfg["tenant_id"])
    cfg["api_base_url"] = validate_url(cfg["api_base_url"], "api_base_url", allow_empty=False)
    cfg["default_branch_id"] = validate_branch_id(cfg["default_branch_id"])

    b = cfg["branding"]
    b["primary_color"] = validate_color(b["primary_color"], "branding.primary_color")
    b["secondary_color"] = validate_color(b["secondary_color"], "branding.secondary_color")
    b["accent_color"] = validate_color(b["accent_color"], "branding.accent_color")
    b["font_family"] = validate_font_family(b["font_family"])
    b["border_radius"] = validate_border_radius(b["border_radius"])

    c = cfg["contact"]
    c["phone"] = validate_text(c["phone"], "contact.phone", allow_empty=True)
    c["email"] = validate_text(c["email"], "contact.email", allow_empty=True)
    if c["email"]:
        _require("@" in c["email"] and "." in c["email"].rsplit("@", 1)[-1],
                 f"contact.email: '{c['email']}' is not a valid email address")
    c["website"] = validate_url(c["website"], "contact.website")

    cfg["legal"]["privacy_policy"] = validate_url(cfg["legal"]["privacy_policy"], "legal.privacy_policy")
    cfg["legal"]["terms"] = validate_url(cfg["legal"]["terms"], "legal.terms")

    for key in ("logo_url", "icon_url", "splash_url"):
        cfg["assets"][key] = validate_url(cfg["assets"].get(key, ""), f"assets.{key}")

    # Deep link domains: explicit list wins, otherwise derived from api_base_url.
    if "deep_links" not in cfg or not isinstance(cfg["deep_links"], dict):
        cfg["deep_links"] = {"domains": []}
    explicit = cfg["deep_links"].get("domains") or []
    if not isinstance(explicit, list):
        raise ProvisioningError("deep_links.domains: must be a list of hostnames")
    if explicit:
        domains = [validate_host(d, f"deep_links.domains[{i}]") for i, d in enumerate(explicit)]
    else:
        domains = [validate_host(urlparse(cfg["api_base_url"]).netloc, "deep_links.host(derived)")]
    cfg["deep_links"]["domains"] = sorted(set(domains))

    return cfg


def validate_host(value: str, field: str) -> str:
    value = (value or "").strip().lower()
    _require(bool(value) and bool(HOST_RE.match(value)) and ".." not in value and len(value) <= 253,
             f"{field}: '{value}' is not a valid hostname for App Links / Universal Links")
    _require("_" not in value and " " not in value,
             f"{field}: '{value}' contains characters forbidden in link domains")
    _require(value.split(".")[0] != "*",
             f"{field}: wildcard hosts are not allowed here; provision explicit tenant domains")
    return value


# ---------------------------------------------------------------------------
# Normalization: legacy flat keys -> canonical nested schema
# ---------------------------------------------------------------------------

def _migrate(target: dict, section: str, new_key: str, old_key: str, raw: dict, warnings: list) -> None:
    """Backfill a legacy top-level key into the canonical nested position.

    The canonical nested spelling always wins; the legacy flat key is used
    only when the nested section did not supply the value.
    """
    if old_key not in raw:
        return
    section_raw = raw.get(section)
    if isinstance(section_raw, dict) and new_key in section_raw:
        return  # canonical spelling already winning.
    target[section][new_key] = raw[old_key]
    warnings.append(
        f"deprecated key '{old_key}' -> '{section}.{new_key}' "
        f"(migrate to canonical schema {CANONICAL_SCHEMA_ID})"
    )


def normalize_config(raw: dict) -> dict:
    """Reduce any accepted config shape (canonical nested or legacy flat) to
    the canonical nested schema defined in docs/MOBILE-WHITELABEL-CONTRACT.md."""
    if not isinstance(raw, dict):
        raise ProvisioningError("configuration payload must be a JSON object")

    warnings = []

    # Unwrap REST envelope only when it clearly carries the payload, not
    # WordPress meta/lists (the server returns {"data": {...}, "meta": {...}}).
    if "data" in raw and isinstance(raw["data"], dict) and "app_identifier" in raw["data"]:
        raw = raw["data"]

    cfg = json.loads(json.dumps(DEFAULTS))  # deep copy

    # Top-level fields.
    for key in ("app_name", "version_name", "version_code", "api_base_url",
                "tenant_id", "default_branch_id"):
        if key in raw:
            cfg[key] = raw[key]

    # app_identifier has no default: it MUST come from the payload (canonical)
    # or from the legacy alias package_name.
    if "app_identifier" in raw:
        cfg["app_identifier"] = raw["app_identifier"]
    elif "package_name" in raw:
        cfg["app_identifier"] = raw["package_name"]
        warnings.append(
            f"deprecated key 'package_name' -> 'app_identifier' "
            f"(migrate to canonical schema {CANONICAL_SCHEMA_ID})"
        )

    # Legacy restaurant_id was an alias of tenant_id.
    if "tenant_id" not in raw and "restaurant_id" in raw:
        cfg["tenant_id"] = raw["restaurant_id"]
        warnings.append(
            f"deprecated key 'restaurant_id' -> 'tenant_id' "
            f"(migrate to canonical schema {CANONICAL_SCHEMA_ID})"
        )

    # Nested canonical sections override, then legacy flat backfill.
    for section in ("branding", "contact", "legal", "assets", "deep_links"):
        section_raw = raw.get(section)
        if isinstance(section_raw, dict):
            for key, value in section_raw.items():
                if key in cfg[section]:
                    cfg[section][key] = value

    _migrate(cfg, "branding", "primary_color", "primary_color", raw, warnings)
    _migrate(cfg, "branding", "secondary_color", "secondary_color", raw, warnings)
    _migrate(cfg, "branding", "accent_color", "accent_color", raw, warnings)
    _migrate(cfg, "branding", "font_family", "font_family", raw, warnings)
    _migrate(cfg, "branding", "border_radius", "border_radius", raw, warnings)
    _migrate(cfg, "contact", "phone", "support_phone", raw, warnings)
    _migrate(cfg, "contact", "email", "support_email", raw, warnings)
    _migrate(cfg, "contact", "website", "website_url", raw, warnings)
    _migrate(cfg, "legal", "privacy_policy", "privacy_policy_url", raw, warnings)
    _migrate(cfg, "legal", "terms", "terms_url", raw, warnings)
    _migrate(cfg, "assets", "logo_url", "logo_url", raw, warnings)
    _migrate(cfg, "assets", "icon_url", "icon_url", raw, warnings)
    _migrate(cfg, "assets", "splash_url", "splash_url", raw, warnings)

    _require("app_identifier" in cfg and cfg["app_identifier"],
             "missing required field 'app_identifier' (canonical) / 'package_name' (legacy)")

    for warning in warnings:
        print(f"[!] Deprecation warning: {warning}")

    return validate_config(cfg)



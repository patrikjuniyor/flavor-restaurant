#!/usr/bin/env python3
"""
Flavor Mobile Brand Provisioning Tool.

Applies the CANONICAL white-label branding configuration (see
docs/MOBILE-WHITELABEL-CONTRACT.md) served by the WordPress REST endpoint
``GET /flavor/v1/mobile/config`` — or supplied via a local JSON file — to the
Flutter, Android, and iOS projects during CI/CD.

Contract guarantees implemented here:

* Both the canonical nested schema and the legacy flat schema are accepted,
  but everything is normalized to the canonical nested shape before use.
* Every value is validated BEFORE it is written (package names, URLs, hex
  colors, version names/codes, slugs). Invalid required values abort the
  build with a non-zero exit code.
* Every value is escaped for the target file format (Dart string literals,
  Android XML attributes, plist XML, Groovy/Gradle strings).
* Android: ``applicationId`` is provisioned per brand, but the Gradle
  ``namespace`` and the Kotlin package tree stay FIXED at
  ``com.flavor.restaurant`` (stable-native-package architecture).
* iOS: ``CFBundleDisplayName`` / ``CFBundleURLName`` are provisioned plist-side;
  the bundle identifier is provisioned into ``project.pbxproj`` when it is
  present (it is generated by ``flutter create`` in CI and may be absent
  from the repo).

Usage:
  python3 provision_brand.py --config-url https://site.example/wp-json/flavor/v1/mobile/config
  python3 provision_brand.py --config-file path/to/brand_config.json
"""


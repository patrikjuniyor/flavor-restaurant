def update_pubspec_yaml(mobile_dir: str, cfg: dict):
    pubspec_path = os.path.join(mobile_dir, "pubspec.yaml")
    if not os.path.exists(pubspec_path):
        print(f"[!] pubspec.yaml not found at {pubspec_path}")
        return

    with open(pubspec_path, "r", encoding="utf-8") as f:
        content = f.read()

    # version_name/version_code are validated, so the YAML line is safe.
    version_line = f"version: {cfg['version_name']}+{cfg['version_code']}"
    content, n = re.subn(r"^version:\s*.*$", version_line, content, count=1, flags=re.MULTILINE)
    if n != 1:
        raise ProvisioningError("pubspec.yaml: could not locate a 'version:' line to update")

    with open(pubspec_path, "w", encoding="utf-8") as f:
        f.write(content)
    print(f"[+] Updated pubspec.yaml version: {cfg['version_name']}+{cfg['version_code']}")


def update_android_branding(mobile_dir: str, cfg: dict):
    """Provision Android: ``applicationId`` per brand, ``namespace`` fixed."""
    build_gradle = os.path.join(mobile_dir, "android", "app", "build.gradle")
    app_id = cfg["app_identifier"]  # already validated

    if os.path.exists(build_gradle):
        with open(build_gradle, "r", encoding="utf-8") as f:
            content = f.read()

        # Enforce the stable-native-package architecture: namespace must match
        # the Kotlin source tree (never brand-dependent).
        ns_match = re.search(r'namespace\s+["\']([^"\']+)["\']', content)
        _require(ns_match, "build.gradle: no 'namespace' declaration found")
        _require(
            ns_match.group(1) == STABLE_NATIVE_PACKAGE,
            f"build.gradle: namespace '{ns_match.group(1)}' != expected stable package "
            f"'{STABLE_NATIVE_PACKAGE}'. The Kotlin source tree is not brand-provisioned; "
            f"keep namespace fixed and vary applicationId only.",
        )

        content, n = re.subn(
            r'applicationId\s+["\'][^"\']+["\']',
            f'applicationId "{escape_gradle_string(app_id)}"',
            content,
            count=1,
        )
        _require(n == 1, "build.gradle: could not locate 'applicationId' to update")

        content, n = re.subn(
            r'versionCode\s+flutterVersionCode\.toInteger\(\)|\bversionCode\s+\d+',
            f"versionCode {cfg['version_code']}",
            content,
            count=1,
        )
        _require(n == 1, "build.gradle: could not locate 'versionCode' to update")

        content, n = re.subn(
            r'versionName\s+flutterVersionName|\bversionName\s+["\'][^"\']*["\']',
            f'versionName "{escape_gradle_string(cfg["version_name"])}"',
            content,
            count=1,
        )
        _require(n == 1, "build.gradle: could not locate 'versionName' to update")

        with open(build_gradle, "w", encoding="utf-8") as f:
            f.write(content)
        print(f"[+] Updated Android build.gradle (applicationId: {app_id}, version: "
              f"{cfg['version_name']} ({cfg['version_code']})) | namespace stable: "
              f"{STABLE_NATIVE_PACKAGE}")

        # Sanity: the Kotlin entry point must exist under the stable package path.
        kotlin_path = os.path.join(
            mobile_dir, "android", "app", "src", "main", "kotlin",
            *STABLE_NATIVE_PACKAGE.split("."), "MainActivity.kt",
        )
        _require(
            os.path.exists(kotlin_path),
            f"Kotlin entry point not found at {kotlin_path}; the native source tree must "
            f"stay in package '{STABLE_NATIVE_PACKAGE}'.",
        )

    manifest_path = os.path.join(mobile_dir, "android", "app", "src", "main", "AndroidManifest.xml")
    if os.path.exists(manifest_path):
        with open(manifest_path, "r", encoding="utf-8") as f:
            m_content = f.read()

        label = escape_xml_text(cfg["app_name"])
        m_content, n = re.subn(
            r'android:label="[^"]*"',
            f'android:label="{label}"',
            m_content,
            count=1,
        )
        _require(n == 1, "AndroidManifest.xml: could not locate android:label to update")
        with open(manifest_path, "w", encoding="utf-8") as f:
            f.write(m_content)
        print(f"[+] Updated Android Manifest app label: {cfg['app_name']}")


def update_ios_branding(mobile_dir: str, cfg: dict):
    app_id = cfg["app_identifier"]  # validated; XML-safe identifier
    app_name = cfg["app_name"]

    # 1) project.pbxproj holds PRODUCT_BUNDLE_IDENTIFIER; it only exists after
    #    `flutter create` runs in CI, so provision it when present.
    pbxproj = os.path.join(mobile_dir, "ios", "Runner.xcodeproj", "project.pbxproj")
    if os.path.exists(pbxproj):
        with open(pbxproj, "r", encoding="utf-8") as f:
            pbx = f.read()
        pbx, n = re.subn(
            r"PRODUCT_BUNDLE_IDENTIFIER\s*=\s*[^;\s]+",
            f"PRODUCT_BUNDLE_IDENTIFIER = {app_id}",
            pbx,
        )
        with open(pbxproj, "w", encoding="utf-8") as f:
            f.write(pbx)
        print(f"[+] Provisioned iOS bundle identifier in project.pbxproj ({n} occurrence(s)): {app_id}")
    else:
        print("[i] ios/Runner.xcodeproj/project.pbxproj not present (generated by flutter "
              "create in CI); bundle identifier will come from CI with --bundle-identifier.")

    # 2) Info.plist: display name + URL name (plists are XML; escape first).
    info_plist = os.path.join(mobile_dir, "ios", "Runner", "Info.plist")
    if os.path.exists(info_plist):
        with open(info_plist, "r", encoding="utf-8") as f:
            plist = f.read()

        plist, n = re.subn(
            r"(<key>CFBundleDisplayName</key>\s*<string>)[^<]*(</string>)",
            lambda m: m.group(1) + escape_xml_text(app_name) + m.group(2),
            plist,
            count=1,
        )
        _require(n == 1, "Info.plist: could not locate CFBundleDisplayName")

        plist, n = re.subn(
            r"(<key>CFBundleURLName</key>\s*<string>)[^<]*(</string>)",
            lambda m: m.group(1) + escape_xml_text(app_id) + m.group(2),
            plist,
            count=1,
        )
        _require(n == 1, "Info.plist: could not locate CFBundleURLName")

        with open(info_plist, "w", encoding="utf-8") as f:
            f.write(plist)
        print(f"[+] Updated iOS Info.plist (display name: '{app_name}', URL name: {app_id})")



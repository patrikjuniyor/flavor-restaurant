#!/usr/bin/env python3
# -*- coding: utf-8 -*-
r"""Generate an ar-partN.py catalogue file from a PHP string map.

Keys in the Arabic file are the exact Persian msgids, which is what makes
hand-editing them a trap: one renamed source string silently orphans its
translation. This builds the file from the live PHP map instead, so a key that
no longer exists in the map aborts the generation, and a msgid is never retyped.

    php dev-tools/build-pot.php
    python3 dev-tools/i18n/build-ar-part.py \
        --part 7 --map '\Flavor\Premium_Assets::strings' --arabic /tmp/ar7.json
    python3 dev-tools/i18n/build-po.py ar
    msgfmt -o flavor/languages/flavor-ar.mo flavor/languages/flavor-ar.po

--arabic is a JSON object of { "<js key>": "<Arabic>" }. Every key in the map
must be covered or the run fails, unless --only-listed is given (used when the
rest of the map already has a translation in another part file).
"""
import argparse
import io
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PLACEHOLDER = re.compile(r"%\d*\$?s")


def dump_map(method):
	"""Run the PHP map method under the theme's mock environment and return it."""
	# The class file is named after the class (\Flavor\Premium_Assets ->
	# inc/class-premium-assets.php), so any map can be dumped without keeping a
	# list of files here — and loading only that one avoids classes whose file
	# extends WP_Customize_Control and fatals outside the Customizer.
	klass = method.split("::")[0].lstrip("\\").split("\\")[-1]
	file = os.path.join(ROOT, "flavor/inc/class-%s.php" % re.sub(r"[^a-z0-9]+", "-", re.sub(r"(?<!^)(?=[A-Z])", "-", klass).lower()).strip("-"))
	if not os.path.isfile(file):
		raise SystemExit("no class file for %s (looked in %s)" % (klass, file))
	script = (
		"require %s;"
		"require_once %s;"
		"echo json_encode(%s(), JSON_UNESCAPED_UNICODE);"
	) % (json.dumps(os.path.join(ROOT, "tests/theme/bootstrap.php")), json.dumps(file), method)
	proc = subprocess.run(["php", "-r", script], cwd=ROOT, capture_output=True, text=True)
	if proc.returncode != 0:
		raise SystemExit("php failed: " + (proc.stderr.strip()[-500:] or "no stderr"))
	tail = proc.stdout.strip().splitlines()
	if not tail:
		raise SystemExit("php printed nothing for " + method)
	return json.loads(tail[-1])


def placeholders(text):
	"""Sorted token list, so "%1$s %2$s" cannot be matched against "%s %s"."""
	return sorted(PLACEHOLDER.findall(text))


def main():
	ap = argparse.ArgumentParser()
	ap.add_argument("--part", required=True, help="part number, e.g. 7")
	ap.add_argument("--map", required=True, help="PHP static method returning the map")
	ap.add_argument("--arabic", required=True, help="JSON file of {js key: arabic}")
	ap.add_argument("--out", default=None)
	ap.add_argument("--only-listed", action="store_true", help="emit just the listed keys")
	ap.add_argument("--note", default="")
	args = ap.parse_args()

	live = dump_map(args.map)
	arabic = json.load(io.open(args.arabic, encoding="utf-8"))

	unknown = sorted(set(arabic) - set(live))
	if unknown:
		raise SystemExit("keys with no entry in the PHP map (a renamed string?): " + ", ".join(unknown))
	if not args.only_listed:
		missing = sorted(set(live) - set(arabic))
		if missing:
			raise SystemExit("map keys with no Arabic supplied: " + ", ".join(missing))

	pairs = []
	for key in live:
		if key not in arabic:
			continue
		source = live[key]
		value = arabic[key]
		if placeholders(source) != placeholders(value):
			raise SystemExit(
				"placeholder mismatch for %s: %s vs %s" % (key, placeholders(source), placeholders(value))
			)
		pairs.append((source, value))

	out = args.out or os.path.join(ROOT, "dev-tools/i18n/ar-part%s.py" % args.part)
	header = [
		"# -*- coding: utf-8 -*-",
		# Raw string: the note can name a PHP class, and \Flavor in a plain
		# docstring is an invalid escape sequence Python warns about.
		'r"""Arabic translations, part %s: %s' % (args.part, (args.note or "generated by dev-tools/i18n/build-ar-part.py")),
		"",
		"Generated by dev-tools/i18n/build-ar-part.py from the live PHP string map",
		"(%s), so the keys are byte-identical to the msgids in flavor.pot and a" % args.map,
		"renamed source string fails the generator instead of orphaning a translation.",
		'"""',
		"",
		"PART_%s = {" % args.part,
	]
	body = ["    %s: %s," % (json.dumps(src, ensure_ascii=False), json.dumps(val, ensure_ascii=False)) for src, val in pairs]
	io.open(out, "w", encoding="utf-8").write("\n".join(header + body + ["}", ""]) + "\n")
	print("%s: %d pairs" % (os.path.basename(out), len(pairs)))
	return 0


if __name__ == "__main__":
	sys.exit(main())

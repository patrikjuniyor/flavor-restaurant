#!/usr/bin/env python3
"""
Parses lcov.info generated by flutter test --coverage,
computes line coverage percentage, enforces a minimum threshold (default 60%),
and optionally writes out a markdown summary and lcov summary.
"""

import sys
import os
import argparse

def parse_lcov(lcov_path):
    if not os.path.exists(lcov_path):
        raise FileNotFoundError(f"LCOV file not found: {lcov_path}")

    total_lines = 0
    covered_lines = 0
    file_records = {}
    current_file = None

    with open(lcov_path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line.startswith("SF:"):
                current_file = line[3:]
                file_records[current_file] = {"total": 0, "covered": 0}
            elif line.startswith("DA:") and current_file:
                parts = line[3:].split(",")
                if len(parts) >= 2:
                    hits = int(parts[1])
                    file_records[current_file]["total"] += 1
                    total_lines += 1
                    if hits > 0:
                        file_records[current_file]["covered"] += 1
                        covered_lines += 1

    overall_pct = (covered_lines / total_lines * 100) if total_lines > 0 else 0.0
    return overall_pct, covered_lines, total_lines, file_records

def main():
    parser = argparse.ArgumentParser(description="Check Flutter test coverage threshold")
    parser.add_argument("--lcov", default="mobile/coverage/lcov.info", help="Path to lcov.info")
    parser.add_argument("--threshold", type=float, default=60.0, help="Minimum coverage threshold in percent")
    parser.add_argument("--summary-file", default=None, help="Optional output markdown summary file")
    args = parser.parse_args()

    pct, covered, total, records = parse_lcov(args.lcov)

    print("==================================================")
    print("Flutter Test Coverage Report")
    print("==================================================")
    print(f"Total Lines:   {total}")
    print(f"Covered Lines: {covered}")
    print(f"Coverage:      {pct:.2f}%")
    print(f"Threshold:     {args.threshold:.2f}%")
    print("==================================================")

    if args.summary_file:
        summary_dir = os.path.dirname(args.summary_file)
        if summary_dir:
            os.makedirs(summary_dir, exist_ok=True)
        with open(args.summary_file, "w", encoding="utf-8") as sf:
            sf.write("# Mobile Test Coverage Summary\n\n")
            status = "PASSED" if pct >= args.threshold else "FAILED"
            badge = "🟢" if pct >= args.threshold else "🔴"
            sf.write(f"**Status**: {badge} {status}\n\n")
            sf.write(f"- **Coverage**: `{pct:.2f}%`\n")
            sf.write(f"- **Threshold**: `{args.threshold:.2f}%`\n")
            sf.write(f"- **Covered Lines**: `{covered}` / `{total}`\n\n")
            sf.write("### Low Coverage Files (< 50%)\n\n")
            sf.write("| File | Coverage | Lines |\n")
            sf.write("| :--- | :---: | :---: |\n")
            low_cov = [
                (f, r["covered"], r["total"], (r["covered"]/r["total"]*100) if r["total"]>0 else 0)
                for f, r in records.items() if (r["covered"]/r["total"]*100 if r["total"]>0 else 0) < 50.0
            ]
            low_cov.sort(key=lambda x: x[3])
            for f, cov_l, tot_l, p in low_cov[:20]:
                sf.write(f"| `{f}` | {p:.1f}% | {cov_l}/{tot_l} |\n")

    if pct < args.threshold:
        print(f"\n❌ Coverage gate failed: {pct:.2f}% is below required threshold of {args.threshold:.2f}%\n", file=sys.stderr)
        sys.exit(1)

    print(f"\n✅ Coverage gate passed: {pct:.2f}% meets or exceeds threshold of {args.threshold:.2f}%\n")
    sys.exit(0)

if __name__ == "__main__":
    main()
